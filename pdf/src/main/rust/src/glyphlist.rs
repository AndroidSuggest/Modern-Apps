#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn mac_roman_differs_from_latin() {
        let m = mac_roman();
        // 0xD5 is right single quote in MacRoman (not Latin-1 'Õ').
        assert_eq!(m.get(&0xD5), Some(&'\u{2019}'));
        assert_eq!(m.get(&0x41), Some(&'A'));
        assert_eq!(m.get(&0x80), Some(&'\u{00C4}'));
    }

    #[test]
    fn symbol_greek() {
        let s = symbol();
        assert_eq!(s.get(&0x61), Some(&'\u{03B1}')); // alpha
        assert_eq!(s.get(&0x70), Some(&'\u{03C0}')); // pi
    }

    #[test]
    fn agl_resolves_names() {
        assert_eq!(agl("Aacute"), Some('\u{00C1}'));
        assert_eq!(agl("bullet"), Some('\u{2022}'));
        assert_eq!(agl("omega"), Some('\u{03C9}'));
    }
}

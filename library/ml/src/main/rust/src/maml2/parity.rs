//! Numeric parity: the v2-lowered sampler plan against the v1 plan.
//!
//! Structural parity (the Phase 1 gate): lowering guarantees identical plans
//! from the file and from the net module — same ops, same arena, same
//! bindings. Full numeric parity (both plans through the CPU reference
//! interpreter over invented weights) needs logical-space invented values
//! packed per layout; that needs the repack inverse, which lives in the
//! emitter. Until that exists, the numeric gate is deferred to
//! shipped-asset parity (onnx_parity on real weights, where both paths read
//! the same trained values through their own layouts and must agree).
//!
//! Lives in-tree (`maml2::parity`) because the plan types are reachable from
//! unit tests; the reference interpreter itself is test-only (`#[cfg(test)]`).

use crate::maml2::{infer, lower, verify};
use crate::nets::supertonic_sampler;
use crate::weights::{self, Tensor as WeightTensor};

/// Read the committed v1 asset's table (shapes + order are exact).
///
/// Returns `None` when the asset is absent (CI without assets): asset-backed
/// gates skip quietly, as the shipped-asset device tests do. Anything else —
/// a present-but-unparseable asset — is a hard error.
fn v1_table() -> Option<(Vec<u8>, Vec<WeightTensor>)> {
    // The test binary runs with CWD = the crate dir; the asset path is
    // relative to the workspace root. `CARGO_MANIFEST_DIR` is the crate dir,
    // so walk up four levels (src/main/rust → ml → library → root).
    let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
        .ancestors()
        .nth(4)
        .expect("workspace root")
        .to_path_buf();
    let path = root.join("speech/src/main/assets/supertonic/supertonic_ve.maml");
    let bytes = match std::fs::read(&path) {
        Ok(bytes) => bytes,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => return None,
        Err(e) => panic!("cannot read {}: {e}", path.display()),
    };
    let parsed = weights::Weights::parse(&bytes, weights::graph::SUPERTONIC_VE)
        .expect("parse the v1 asset");
    let table = parsed.offsets();
    let tensors: Vec<WeightTensor> =
        (0..table.len()).map(|i| table.tensor(i).expect("tensor")).collect();
    Some((parsed.data().to_vec(), tensors))
}

/// The v2 plan lowered from the emitted file. `None` when the v2 file is
/// absent (it is generated by `emit_sampler_maml2`, not committed): gates
/// skip quietly.
fn v2_plan() -> Option<crate::nets::Plan> {
    let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
        .ancestors()
        .nth(4)
        .expect("workspace root")
        .to_path_buf();
    let path = root.join("speech/src/main/assets/supertonic/supertonic_ve.maml2");
    let bytes = match std::fs::read(&path) {
        Ok(bytes) => bytes,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => return None,
        Err(e) => panic!("cannot read {}: {e}", path.display()),
    };
    let verified = verify::verify(&bytes).expect("verify");
    let inferred = infer::infer(&verified).expect("infer");
    let bridge = lower::V2Weights::new(&verified).expect("bridge");
    Some(lower::lower(&verified, &inferred[0], &bridge, 0).expect("lower"))
}

/// The every-tensor rule holds on the v2 path: lowering proves coverage
/// structurally, and the builder's own gate stays armed. Skips quietly when
/// the v2 file is absent (it is generated, not committed).
#[test]
fn lowering_proves_every_weight_read() {
    let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
        .ancestors()
        .nth(4)
        .expect("workspace root")
        .to_path_buf();
    let path = root.join("speech/src/main/assets/supertonic/supertonic_ve.maml2");
    let bytes = match std::fs::read(&path) {
        Ok(bytes) => bytes,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => return,
        Err(e) => panic!("cannot read {}: {e}", path.display()),
    };
    let verified = verify::verify(&bytes).expect("verify");
    let inferred = infer::infer(&verified).expect("infer");
    let bridge = lower::V2Weights::new(&verified).expect("bridge");
    // A bridge over the full tensor table serves every tensor.
    assert_eq!(bridge.payloads().len(), verified.tensor_count);
    // Every buffered tensor is named by a node (the rule `lower` enforces).
    let model = verified.model;
    let tensors = model.tensors().expect("tensors");
    let graphs = model.graphs().expect("graphs");
    let graph = graphs.get(0);
    let nodes = graph.nodes().expect("nodes");
    let mut named = vec![false; tensors.len()];
    for n in 0..nodes.len() {
        let node = nodes.get(n);
        if let Some(inputs) = node.inputs() {
            for i in 0..inputs.len() {
                let t = inputs.get(i) as usize;
                if t < named.len() {
                    named[t] = true;
                }
            }
        }
    }
    for t in 0..tensors.len() {
        if tensors.get(t).buffer() != -1 {
            assert!(named[t], "weight tensor {t} is named by no node");
        }
    }
}

/// Barrier schedule comparison (spec 7.5 precursor): the lowered plan must
/// schedule identically to the v1 plan — same ops, same hazards, same count.
/// This is the measurement `report_barriers` will quote once the recorder is
/// wired (Phase 3). Skips quietly when either asset is absent.
#[test]
fn lowered_plan_schedules_like_v1() {
    use crate::nets::schedule;
    let Some((_data, tensors)) = v1_table() else {
        return;
    };
    let source = crate::nets::tests::Shapes::new(tensors.len());
    let v1plan = supertonic_sampler::build(&source, 49, 55).expect("build v1");
    let Some(plan) = v2_plan() else {
        return;
    };
    let v1schedule = schedule::schedule(&v1plan);
    let schedule = schedule::schedule(&plan);
    // Identical geometry through the same scheduler must give identical
    // barrier placement (addresses differ, hazards do not).
    assert_eq!(schedule.barriers(), v1schedule.barriers(), "same barrier count");
    assert!(schedule::is_sound(&plan, &schedule).is_ok());
    println!(
        "sampler barriers: {} of {} ops (v1: {} of {})",
        schedule.barriers(),
        plan.ops.len(),
        v1schedule.barriers(),
        v1plan.ops.len()
    );
}

/// True numeric parity: the v2-lowered plan against the v1 plan, same
/// interpreter, same invented inputs, real weights both sides.
///
/// Both plans run through `run_multi` on their own blob (v1 data section vs
/// bridge blob) — different address spaces, same values, since kernels are
/// NCHW in both files. The arithmetic is identical kind-for-kind (the
/// blocked rewrite qualifies nothing on an all-NCHW file), so the outputs
/// must be bit-exact, not within tolerance: any divergence is a loader bug
/// (wrong offset, dropped res/shift, permuted kernel), never rounding.
/// Skips quietly when either asset is absent.
#[test]
fn v2_plan_matches_v1_bit_exact() {
    let Some((v1data, tensors)) = v1_table() else {
        return;
    };
    let source = crate::nets::tests::Shapes::new(tensors.len());
    let v1plan = supertonic_sampler::build(&source, 49, 55).expect("build v1");
    let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
        .ancestors()
        .nth(4)
        .expect("workspace root")
        .to_path_buf();
    let path = root.join("speech/src/main/assets/supertonic/supertonic_ve.maml2");
    let bytes = match std::fs::read(&path) {
        Ok(bytes) => bytes,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => return,
        Err(e) => panic!("cannot read {}: {e}", path.display()),
    };
    let verified = verify::verify(&bytes).expect("verify");
    let inferred = infer::infer(&verified).expect("infer");
    let bridge = lower::V2Weights::new(&verified).expect("bridge");
    let plan = lower::lower(&verified, &inferred[0], &bridge, 0).expect("lower");
    // Same invented inputs both sides: the seven sampler inputs at the
    // recorded shape, distinct and asymmetric about zero.
    let shapes = [
        (144usize, 1usize, 49usize),
        (256, 1, 55),
        (1024, 1, 50),
        (256, 1, 50),
        (2048, 1, 1),
        (64, 1, 49),
        (64, 1, 55),
    ];
    let inputs: Vec<Vec<f32>> = shapes
        .iter()
        .enumerate()
        .map(|(k, (c, h, w))| {
            (0..c * h * w)
                .map(|i| (i as f32 * 0.7 + k as f32 * 1.7).sin() * 0.8 + 0.1)
                .collect()
        })
        .collect();
    let refs: Vec<&[f32]> = inputs.iter().map(|v| v.as_slice()).collect();
    let v1out = crate::nets::reference::run_multi(&v1plan, &v1data, &refs).expect("run v1");
    let v2out = crate::nets::reference::run_multi(&plan, &bridge.blob(), &refs).expect("run v2");
    // The zero oracle: invented inputs through 212 real-weight ops cannot be
    // zero; an all-zeros output means the inputs never reached the graph.
    assert!(
        v1out.iter().flat_map(|v| v.iter()).any(|&v| v != 0.0),
        "the v1 interpreter output is all zeros"
    );
    assert_eq!(v2out.len(), v1out.len(), "same output count");
    for (index, (a, b)) in v1out.iter().zip(v2out.iter()).enumerate() {
        assert_eq!(a.len(), b.len(), "output {index} length");
        for (at, (x, y)) in a.iter().zip(b.iter()).enumerate() {
            assert!(x == y, "output {index} element {at}: v1 {x} vs v2 {y}");
        }
    }
}
